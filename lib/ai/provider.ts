import { GoogleGenAI } from "@google/genai";
import Groq from "groq-sdk";

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

export type AIProviderType = "groq" | "google";

export interface AIProviderConfig {
  provider: AIProviderType;
  apiKey: string;
  model: string;
  maxRetries: number;
  retryDelayMs: number;
  maxOutputTokens: number;
  temperature: number;
}

export interface AIResponse {
  text: string;
  provider: AIProviderType;
  model: string;
  latency_ms: number;
}

function getDefaultConfig(): AIProviderConfig {
  const provider: AIProviderType =
    process.env.LLM_PROVIDER === "groq" ? "groq" : "google";

  if (provider === "groq") {
    return {
      provider: "groq",
      apiKey: process.env.GROQ_API_KEY || "",
      model: "qwen/qwen3.6-27b",
      maxRetries: 3,
      retryDelayMs: 5000,
      maxOutputTokens: 16384,
      temperature: 0.1,
    };
  }

  return {
    provider: "google",
    apiKey: process.env.GOOGLE_AI_STUDIO_API_KEY || "",
    model: "gemini-3.6-flash",
    maxRetries: 3,
    retryDelayMs: 5000,
    maxOutputTokens: 16384,
    temperature: 0.1,
  };
}

// ---- GROQ ----

async function callGroq(
  config: AIProviderConfig,
  prompt: string,
  base64Images: string[]
): Promise<AIResponse> {
  if (!config.apiKey) throw new Error("Server missing GROQ_API_KEY");

  const groq = new Groq({ apiKey: config.apiKey });

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const content: any[] = [{ type: "text", text: prompt }];
  for (const img of base64Images) {
    let url = img;
    if (!img.startsWith("data:")) {
      url = `data:image/jpeg;base64,${img}`;
    }
    content.push({ type: "image_url", image_url: { url } });
  }

  let attempts = 0;
  while (attempts < config.maxRetries) {
    const start = Date.now();
    try {
      const completion = await groq.chat.completions.create({
        model: config.model,
        messages: [{ role: "user", content }],
        temperature: config.temperature,
        max_tokens: config.maxOutputTokens,
        response_format: { type: "json_object" },
      });

      const text = completion.choices?.[0]?.message?.content;
      if (!text) throw new Error("No text generated by Groq");

      return {
        text: text.replace(/```json/g, "").replace(/```/g, "").trim(),
        provider: "groq",
        model: config.model,
        latency_ms: Date.now() - start,
      };
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
    } catch (error: any) {
      if (error.status === 429) {
        attempts++;
        console.warn(
          `Groq rate limited. Retry in ${config.retryDelayMs}ms (${attempts}/${config.maxRetries})`
        );
        await sleep(config.retryDelayMs);
        continue;
      }
      if (attempts >= config.maxRetries - 1) throw error;
      attempts++;
      await sleep(2000);
    }
  }
  throw new Error("Max retries exceeded for Groq");
}

// ---- GOOGLE ----

async function callGoogle(
  config: AIProviderConfig,
  prompt: string,
  base64Images: string[]
): Promise<AIResponse> {
  if (!config.apiKey) throw new Error("Server missing GOOGLE_AI_STUDIO_API_KEY");

  const ai = new GoogleGenAI({ apiKey: config.apiKey });

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const parts: any[] = [{ text: prompt }];
  for (const img of base64Images) {
    const match = img.match(/^data:(image\/[a-zA-Z+]+);base64,/);
    const mimeType = match ? match[1] : "image/jpeg";
    const base64Data = img.includes(",") ? img.split(",")[1] : img;
    parts.push({ inlineData: { data: base64Data, mimeType } });
  }

  let attempts = 0;
  while (attempts < config.maxRetries) {
    const start = Date.now();
    try {
      const response = await ai.models.generateContent({
        model: config.model,
        contents: parts,
        config: {
          temperature: config.temperature,
          maxOutputTokens: config.maxOutputTokens,
          responseMimeType: "application/json",
        },
      });

      const text = response.text;
      if (!text) throw new Error("No text generated by Google model");

      return {
        text: text.replace(/```json/g, "").replace(/```/g, "").trim(),
        provider: "google",
        model: config.model,
        latency_ms: Date.now() - start,
      };
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
    } catch (error: any) {
      if (error.status === 429) {
        attempts++;
        console.warn(
          `Google rate limited. Retry in ${config.retryDelayMs}ms (${attempts}/${config.maxRetries})`
        );
        await sleep(config.retryDelayMs);
        continue;
      }
      if (attempts >= config.maxRetries - 1) throw error;
      attempts++;
      await sleep(2000);
    }
  }
  throw new Error("Max retries exceeded for Google");
}

// ---- PUBLIC API ----

export async function callAI(
  prompt: string,
  base64Images: string[],
  configOverrides?: Partial<AIProviderConfig>
): Promise<AIResponse> {
  const config = { ...getDefaultConfig(), ...configOverrides };

  if (config.provider === "groq") {
    return callGroq(config, prompt, base64Images);
  }
  return callGoogle(config, prompt, base64Images);
}

export function getProviderConfig(): AIProviderConfig {
  return getDefaultConfig();
}
